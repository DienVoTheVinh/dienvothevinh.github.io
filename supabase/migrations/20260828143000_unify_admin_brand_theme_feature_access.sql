create table if not exists private.vm_feature_catalog (
  feature_key text primary key,
  parent_key text references private.vm_feature_catalog(feature_key) on delete restrict,
  kind text not null default 'route' check (kind in ('route','capability','system')),
  label text not null,
  description text not null default '',
  group_key text not null default 'general',
  sort_order integer not null default 0,
  default_state text not null default 'hidden' check (default_state in ('shown','locked','hidden')),
  is_delegable boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vm_feature_catalog_key_check check (feature_key ~ '^[a-z][a-z0-9_.]{1,79}$')
);

create table if not exists private.vm_feature_role_rules (
  role_scope text not null check (role_scope in ('admin','teacher','assistant','student','parent')),
  feature_key text not null references private.vm_feature_catalog(feature_key) on delete cascade,
  state text not null check (state in ('shown','locked','hidden')),
  updated_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key(role_scope,feature_key)
);

create table if not exists private.vm_feature_user_rules (
  user_id uuid not null references public.profiles(id) on delete cascade,
  feature_key text not null references private.vm_feature_catalog(feature_key) on delete cascade,
  state text not null check (state in ('shown','locked','hidden')),
  updated_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key(user_id,feature_key)
);

create table if not exists private.vm_feature_policy_audit (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  target_role text,
  target_user_id uuid references public.profiles(id) on delete set null,
  feature_key text,
  action text not null,
  previous_state text,
  next_state text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists vm_feature_policy_audit_target_idx
  on private.vm_feature_policy_audit(target_user_id,created_at desc);

