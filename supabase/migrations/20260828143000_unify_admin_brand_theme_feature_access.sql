  if nullif(btrim(v_portal.name),'') is null or nullif(btrim(v_portal.short_name),'') is null or nullif(btrim(v_portal.home_path),'') is null then raise exception 'tenant_incomplete' using errcode='22023'; end if;
  update public.exam_portals set is_active=true,exam_focus_mode=coalesce(p_exam_focus,false),deployed_at=now(),deployed_by=v_actor,updated_at=now() where id=p_portal_id returning * into v_portal;
