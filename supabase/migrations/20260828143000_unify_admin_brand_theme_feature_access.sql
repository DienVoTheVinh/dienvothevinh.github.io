create or replace function private.vm_effective_feature_state(
  p_user_id uuid,
  p_feature_key text
)
returns text
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_role text;
  v_state text;
begin
  select role into v_role from public.profiles where id=p_user_id;
  if v_role is null then return 'hidden'; end if;
  if v_role='admin' then return 'shown'; end if;

  select rule.state into v_state
  from private.vm_feature_user_rules rule
  where rule.user_id=p_user_id and rule.feature_key=p_feature_key;
  if found then return v_state; end if;

  select rule.state into v_state
  from private.vm_feature_role_rules rule
  where rule.role_scope=v_role and rule.feature_key=p_feature_key;
  if found then return v_state; end if;

  select catalog.default_state into v_state
  from private.vm_feature_catalog catalog
  where catalog.feature_key=p_feature_key;
  return coalesce(v_state,'hidden');
end;
$function$;

create or replace function private.vm_has_feature(p_user_id uuid,p_feature_key text)
returns boolean
language sql
stable
security definer
set search_path=''
as $function$
  select case
    when p_user_id is null then false
    when public.is_admin() and p_user_id=(select auth.uid()) then true
    else private.vm_effective_feature_state(p_user_id,p_feature_key)='shown'
  end;
$function$;

revoke all on function private.vm_effective_feature_state(uuid,text) from public,anon,authenticated;
