  on conflict(portal_id,role_scope,feature_key) do update set state=excluded.state,updated_by=excluded.updated_by,updated_at=excluded.updated_at;
  return jsonb_build_object('id',v_portal.id,'slug',v_portal.slug,'is_active',v_portal.is_active,'exam_focus_mode',v_portal.exam_focus_mode,'deployed_at',v_portal.deployed_at);
