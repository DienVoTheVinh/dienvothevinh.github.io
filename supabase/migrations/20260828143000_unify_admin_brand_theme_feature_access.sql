create or replace function public.vm_admin_feature_matrix(p_user_id uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $function$
begin
  if (select auth.uid()) is null or not (select public.is_admin()) then
    raise exception 'admin_required' using errcode='42501';
  end if;
  return jsonb_build_object(
    'catalog',coalesce((select jsonb_agg(to_jsonb(c) order by c.group_key,c.sort_order,c.feature_key) from private.vm_feature_catalog c),'[]'::jsonb),
    'role_rules',coalesce((select jsonb_agg(to_jsonb(r) order by r.role_scope,c.sort_order) from private.vm_feature_role_rules r join private.vm_feature_catalog c using(feature_key)),'[]'::jsonb),
    'user_rules',coalesce((select jsonb_agg(to_jsonb(u) order by c.sort_order) from private.vm_feature_user_rules u join private.vm_feature_catalog c using(feature_key) where u.user_id=p_user_id),'[]'::jsonb),
    'effective',coalesce((select jsonb_agg(jsonb_build_object('feature_key',c.feature_key,'state',private.vm_effective_feature_state(p_user_id,c.feature_key)) order by c.sort_order) from private.vm_feature_catalog c where p_user_id is not null),'[]'::jsonb)
  );
end;
$function$;

create or replace function public.vm_admin_save_role_feature_rules(p_role text,p_rules jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path=''
as $function$
declare v_actor uuid:=(select auth.uid()); v_item jsonb; v_previous text;
begin
  if v_actor is null or not (select public.is_admin()) then raise exception 'admin_required' using errcode='42501'; end if;
  if p_role not in ('teacher','assistant','student','parent') or p_rules is null or jsonb_typeof(p_rules) is distinct from 'array' then raise exception 'feature_rules_invalid' using errcode='22023'; end if;
  for v_item in select value from jsonb_array_elements(p_rules) loop
    if coalesce(v_item->>'feature_key','')='' or coalesce(v_item->>'state','') not in ('shown','locked','hidden')
      or not exists(select 1 from private.vm_feature_catalog c where c.feature_key=v_item->>'feature_key' and c.is_delegable) then
      raise exception 'feature_rule_invalid' using errcode='22023';
    end if;
    select state into v_previous from private.vm_feature_role_rules where role_scope=p_role and feature_key=v_item->>'feature_key';
    insert into private.vm_feature_role_rules(role_scope,feature_key,state,updated_by,updated_at)
    values(p_role,v_item->>'feature_key',v_item->>'state',v_actor,now())
    on conflict(role_scope,feature_key) do update set state=excluded.state,updated_by=excluded.updated_by,updated_at=excluded.updated_at;
    insert into private.vm_feature_policy_audit(actor_id,target_role,feature_key,action,previous_state,next_state)
    values(v_actor,p_role,v_item->>'feature_key','role_rule_saved',v_previous,v_item->>'state');
  end loop;
  return public.vm_admin_feature_matrix(null);
end;
$function$;

create or replace function public.vm_admin_save_user_feature_rules(p_user_id uuid,p_rules jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path=''
as $function$
declare v_actor uuid:=(select auth.uid()); v_item jsonb; v_previous text; v_state text;
begin
  if v_actor is null or not (select public.is_admin()) then raise exception 'admin_required' using errcode='42501'; end if;
  if p_user_id is null or p_rules is null or jsonb_typeof(p_rules) is distinct from 'array' or not exists(select 1 from public.profiles where id=p_user_id) then raise exception 'feature_rules_invalid' using errcode='22023'; end if;
  if exists(select 1 from public.profiles where id=p_user_id and role='admin') then raise exception 'admin_policy_immutable' using errcode='22023'; end if;
  for v_item in select value from jsonb_array_elements(p_rules) loop
    v_state:=coalesce(v_item->>'state','inherit');
    if coalesce(v_item->>'feature_key','')='' or v_state not in ('inherit','shown','locked','hidden')
      or not exists(select 1 from private.vm_feature_catalog c where c.feature_key=v_item->>'feature_key' and c.is_delegable) then
      raise exception 'feature_rule_invalid' using errcode='22023';
    end if;
    select state into v_previous from private.vm_feature_user_rules where user_id=p_user_id and feature_key=v_item->>'feature_key';
    if v_state='inherit' then
      delete from private.vm_feature_user_rules where user_id=p_user_id and feature_key=v_item->>'feature_key';
    else
      insert into private.vm_feature_user_rules(user_id,feature_key,state,updated_by,updated_at)
      values(p_user_id,v_item->>'feature_key',v_state,v_actor,now())
      on conflict(user_id,feature_key) do update set state=excluded.state,updated_by=excluded.updated_by,updated_at=excluded.updated_at;
    end if;
    insert into private.vm_feature_policy_audit(actor_id,target_user_id,feature_key,action,previous_state,next_state)
    values(v_actor,p_user_id,v_item->>'feature_key','user_rule_saved',v_previous,nullif(v_state,'inherit'));
  end loop;
  return public.vm_admin_feature_matrix(p_user_id);
end;
$function$;

create or replace function public.vm_admin_deploy_tenant(p_portal_id uuid,p_exam_focus boolean default false)
returns jsonb
language plpgsql
volatile
security definer
set search_path=''
as $function$
declare v_actor uuid:=(select auth.uid()); v_portal public.exam_portals%rowtype;
begin
  if v_actor is null or not (select public.is_admin()) then raise exception 'admin_required' using errcode='42501'; end if;
  select * into v_portal from public.exam_portals where id=p_portal_id for update;
  if v_portal.id is null then raise exception 'tenant_not_found' using errcode='P0002'; end if;
  if v_portal.experience_mode<>'full_site' then raise exception 'tenant_full_site_required' using errcode='22023'; end if;
