    raise exception 'bank_daily_upload_limit' using errcode='54000';
  end if;
  v_hash:=encode(extensions.digest(convert_to(v_raw,'UTF8'),'sha256'),'hex');
  v_stable:='QBD-'||upper(substr(v_hash,1,24));
  insert into private.vm_question_bank_documents(stable_id,content_hash,source_kind,title,province,exam_year,exam_kind,tags,original_filename,raw_tex,metadata,provenance,status,created_by,updated_at)
  values(v_stable,v_hash,case when p_document->>'source_kind' in ('topic_pack','mock_exam','manual','other') then p_document->>'source_kind' else 'other' end,
    left(coalesce(nullif(p_document->>'title',''),nullif(p_document->>'original_filename',''),'Nguồn TeX chờ duyệt'),240),
    left(nullif(p_document->>'province',''),160),nullif(p_document->>'exam_year','')::integer,left(nullif(p_document->>'exam_kind',''),160),'{}'::text[],left(nullif(p_document->>'original_filename',''),500),v_raw,
    coalesce(p_document->'metadata','{}'::jsonb)||jsonb_build_object('import_state','pending_review','delegated_upload',true),
    coalesce(p_document->'provenance','{}'::jsonb)||jsonb_build_object('uploaded_by',v_uid),
    'quarantined',v_uid,now())
  on conflict(content_hash) do update set updated_at=now()
  returning id,status into v_id,v_status;
  insert into private.vm_feature_policy_audit(actor_id,target_user_id,feature_key,action,details)
  values(v_uid,v_uid,'question_bank.import_tex','delegated_tex_upload',jsonb_build_object('document_id',v_id,'content_hash',v_hash));
  return jsonb_build_object('document_id',v_id,'status',v_status,'pending_review',v_status='quarantined');
exception when invalid_text_representation then
  raise exception 'bank_document_metadata_invalid' using errcode='22023';
end;
$function$;

create or replace function public.vm_bank_download_tex(p_document_id uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path=''
as $function$
declare v_uid uuid:=(select auth.uid()); v_result jsonb;
begin
  if v_uid is null or not private.vm_has_feature(v_uid,'question_bank.download_tex') then raise exception 'bank_download_permission_required' using errcode='42501'; end if;
  select jsonb_build_object('id',d.id,'title',d.title,'original_filename',d.original_filename,'raw_tex',d.raw_tex,'source_kind',d.source_kind,'updated_at',d.updated_at)
  into v_result from private.vm_question_bank_documents d where d.id=p_document_id and d.status<>'archived';
  if v_result is null then raise exception 'bank_document_not_found' using errcode='P0002'; end if;
  insert into private.vm_feature_policy_audit(actor_id,target_user_id,feature_key,action,details)
  values(v_uid,v_uid,'question_bank.download_tex','tex_download',jsonb_build_object('document_id',p_document_id));
  return v_result;
end;
$function$;

