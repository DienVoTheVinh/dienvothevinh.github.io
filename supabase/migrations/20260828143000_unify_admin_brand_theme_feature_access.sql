language plpgsql
volatile
security definer
set search_path=''
as $function$
declare v_uid uuid:=(select auth.uid()); v_raw text:=coalesce(p_document->>'raw_tex',''); v_hash text; v_id uuid; v_stable text; v_status text;
begin
  if v_uid is null or not private.vm_has_feature(v_uid,'question_bank.import_tex') then raise exception 'bank_import_permission_required' using errcode='42501'; end if;
  if p_document is null or jsonb_typeof(p_document) is distinct from 'object' then raise exception 'bank_document_metadata_invalid' using errcode='22023'; end if;
  if octet_length(v_raw) not between 1 and 10000000 then raise exception 'bank_document_size_invalid' using errcode='22023'; end if;
  if jsonb_typeof(coalesce(p_document->'metadata','{}'::jsonb)) is distinct from 'object'
    or jsonb_typeof(coalesce(p_document->'provenance','{}'::jsonb)) is distinct from 'object'
