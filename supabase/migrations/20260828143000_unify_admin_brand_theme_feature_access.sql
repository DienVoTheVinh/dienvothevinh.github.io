create or replace function public.vm_my_feature_access(p_portal_id uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_uid uuid:=(select auth.uid());
  v_role text;
  v_member_role text;
  v_items jsonb;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501'; end if;
  select role into v_role from public.profiles where id=v_uid;
  if v_role is null then raise exception 'profile_required' using errcode='42501'; end if;
  if p_portal_id is not null and v_role<>'admin' then
    select m.member_role into v_member_role
    from public.exam_portal_members m
    join public.exam_portals p on p.id=m.portal_id
    where m.portal_id=p_portal_id
      and m.user_id=v_uid
      and p.is_active
      and p.experience_mode='full_site';
    if not found then p_portal_id:=null; end if;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'feature_key',c.feature_key,
    'state',case
      when global_state='hidden' or tenant_state='hidden' then 'hidden'
      when global_state='locked' or tenant_state='locked' then 'locked'
      else 'shown' end,
    'source',case when tenant_state<>'shown' then 'portal' when u.feature_key is not null then 'user' else 'role' end
  ) order by c.sort_order,c.feature_key),'[]'::jsonb)
  into v_items
  from private.vm_feature_catalog c
  left join private.vm_feature_user_rules u on u.user_id=v_uid and u.feature_key=c.feature_key
  cross join lateral (select private.vm_effective_feature_state(v_uid,c.feature_key) global_state) g
  cross join lateral (
    select coalesce((
      select r.state from public.exam_portal_feature_rules r
      where r.portal_id=p_portal_id and r.feature_key=c.feature_key
        and (r.role_scope='*' or r.role_scope=v_role or r.role_scope=v_member_role)
      order by case
        when v_member_role is not null and r.role_scope=v_member_role then 0
        when r.role_scope=v_role then 1
        else 2
      end,r.updated_at desc limit 1
    ),'shown') tenant_state
  ) t;

  return jsonb_build_object(
    'items',v_items,
    'bank',jsonb_build_object(
      'can_use',private.vm_has_feature(v_uid,'question_bank.use'),
      'can_report',private.vm_has_feature(v_uid,'question_bank.report'),
      'can_import',private.vm_has_feature(v_uid,'question_bank.import_tex'),
      'can_download_tex',private.vm_has_feature(v_uid,'question_bank.download_tex'),
      'can_manage',private.vm_has_feature(v_uid,'question_bank.manage'),
      'can_manage_id_schema',private.vm_has_feature(v_uid,'question_bank.id_schema_manage'),
      'is_admin',v_role='admin'
    )
  );
end;
$function$;

